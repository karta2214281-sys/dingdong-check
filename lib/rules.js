const RULES = [...REPEAT, ...DE_DI_DE, ...HOMOPHONE, ...ZAI_TO_ZAI, ...ZAI2_TO_ZAI].map((rule) => ({
  cat: 'typo',
  level: 'err',
  ...rule
}));

// 跑所有規則，傳回找到的修正（還沒處理重疊）
function runRules(text) {
  const out = [];
  for (const rule of RULES) {
    rule.re.lastIndex = 0;
    let match;
    while ((match = rule.re.exec(text)) !== null) {
      if (match[0].length === 0) {
        rule.re.lastIndex++;
        continue;
      }
      const prefix = rule.pre ? match[1] : '';
      const start = match.index + prefix.length;
      const from = match[0].slice(prefix.length);
      if (!from) continue;
      const ctx = { m: match, text, start, from, prefix };
      if (rule.skip && rule.skip(ctx)) continue;
      const level = typeof rule.level === 'function' ? rule.level(ctx) : rule.level;
      const why = typeof rule.why === 'function' ? rule.why(ctx) : rule.why;
      out.push({ cat: rule.cat, level, start, len: from.length, from, to: rule.to, why });
    }
  }
  return out;
}

module.exports = { runRules };
